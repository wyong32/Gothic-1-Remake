              <dt>Can I complete quests for other camps after joining one?</dt>
              <dd>
                No. Once you swear your final oath in Chapter 1, all other camp-specific admission
                quests instantly fail and leave your journal. General worldly side quests remain
                active.
              </dd>
            </div>
            <div class="faq-item">
              <dt>I lost Diego's Old Mine supply list. What should I do?</dt>
              <dd>
                Check inventory under the <strong>Documents</strong> tab. If you gave the list to
                Lares for the New Camp betrayal route, talk to him again to retrieve the modified list
                before returning to Diego.
              </dd>
            </div>
            <div class="faq-item">
              <dt>Why won't the Swamp Camp Gurus talk to me?</dt>
              <dd>
                Gurus like Baal Namib and Baal Tyon value meditation. Forcing conversation gets ignored
                — stand nearby and wait for an external event or NPC (e.g. Lester) to prompt them to
                acknowledge you.
              </dd>
            </div>
            <div class="faq-item">
              <dt>Should I finish all camp admission quests before joining?</dt>
              <dd>
                Yes, if you want maximum Chapter 1 XP and ore. See the
                <RouterLink to="/beginner">Beginner guide</RouterLink> double-dipping method — only the
                final oath is permanent.
              </dd>
